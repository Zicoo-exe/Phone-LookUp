// Function to get country details from phone number
function getCountryDetails(phone) {
    for (const [code, data] of Object.entries(PHONE_DATABASE)) {
        if (phone.startsWith(code)) {
            return {
                countryCode: code,
                country: data.country,
                flag: data.flag,
                timezone: data.timezone,
                carriers: data.carriers
            };
        }
    }
    return null;
}

// Function to identify carrier based on area code
function identifyCarrier(phone, countryDetails) {
    if (!countryDetails) return 'Unknown';
    
    const carriers = countryDetails.carriers;
    let areaCode = '';
    
    // Extract area code (typically 2-3 digits after country code)
    const phoneWithoutCode = phone.replace(countryDetails.countryCode, '').substring(0, 3);
    
    return carriers[phoneWithoutCode] || 'Various / Unknown Carrier';
}

// Format phone number
function formatPhoneNumber(phone) {
    const cleaned = phone.replace(/\D/g, '');
    
    if (cleaned.length === 10) return `(${cleaned.slice(0, 3)}) ${cleaned.slice(3, 6)}-${cleaned.slice(6)}`;
    if (cleaned.length === 11) return `+${cleaned[0]} (${cleaned.slice(1, 4)}) ${cleaned.slice(4, 7)}-${cleaned.slice(7)}`;
    
    return phone;
}

// Validate phone number format
function validatePhoneNumber(phone) {
    const cleanedPhone = phone.replace(/\D/g, '');
    return cleanedPhone.length >= 10 && cleanedPhone.length <= 15;
}

// Determine phone number type
function getPhoneType(phone) {
    const areaCode = phone.substring(2, 5);
    
    if (['800', '888', '877', '866', '855', '844', '833'].includes(areaCode)) {
        return 'Toll-Free';
    } else if (['911', '411', '511', '711'].includes(areaCode)) {
        return 'Service Number';
    } else if (['700', '710', '950', '951'].includes(areaCode)) {
        return 'Reserved';
    } else {
        const secondDigit = phone[1];
        if (secondDigit === '2' || secondDigit === '9') {
            return 'Likely Landline';
        } else if (secondDigit === '3' || secondDigit === '4' || secondDigit === '5' || secondDigit === '6' || secondDigit === '7' || secondDigit === '8') {
            return 'Likely Mobile';
        }
    }
    
    return 'Unknown Type';
}

// Get possible phone formats
function getPossibleFormats(phone) {
    const cleaned = phone.replace(/\D/g, '');
    const formats = [
        cleaned,
        `+${cleaned}`,
        `+${cleaned.slice(0, 1)} ${cleaned.slice(1, 4)} ${cleaned.slice(4, 7)} ${cleaned.slice(7)}`,
        `(${cleaned.slice(0, 3)}) ${cleaned.slice(3, 6)}-${cleaned.slice(6)}`
    ];
    
    return [...new Set(formats)].join('<br>');
}
